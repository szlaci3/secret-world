import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises'

// Reproducible import: npm pack @tabler/icons@3.46.0 --pack-destination artifacts
// then tar -xf artifacts/tabler-icons-3.46.0.tgz -C artifacts
const root = 'artifacts/package'
const metadata = JSON.parse(await readFile(`${root}/icons.json`, 'utf8'))
const categories = new Set(['Animals', 'Buildings', 'Food', 'Nature', 'Media', 'Vehicles', 'Sport', 'Weather', 'Map', 'Health', 'Devices', 'Electrical', 'E-commerce', 'Games', 'Communication', 'Computers', 'Photography'])
const legacy = ['settings', 'paperclip', 'clock', 'folder', 'briefcase', 'calculator', 'device-floppy', 'bulb', 'bell', 'book']
const entries = Object.values(metadata).filter(icon => legacy.includes(icon.name) || icon.styles.filled ||
  (categories.has(icon.category) && !/(-off|-\d+)$/.test(icon.name)))
await mkdir('public/tabler', { recursive: true })
const catalog = {}
for (const icon of entries.sort((a, b) => a.name.localeCompare(b.name))) {
  const style = icon.styles.filled ? 'filled' : 'outline'
  // Keep the original ten byte-for-byte, including the outline paperclip.
  const source = legacy.includes(icon.name) ? `src/assets/tabler/${icon.name}.svg` : `${root}/icons/${style}/${icon.name}.svg`
  await copyFile(source, `public/tabler/${icon.name}.svg`)
  catalog[icon.name] = { category: icon.category, tags: icon.tags.map(String), style }
}
await mkdir('src/icons', { recursive: true })
await writeFile('src/icons/catalog.json', JSON.stringify(catalog) + '\n')
await writeFile('src/icons/names.ts', '// Generated by scripts/import-icon-catalog.mjs.\nexport const catalogNames = ' + JSON.stringify(Object.keys(catalog)) + ' as const\n')
console.log(`Imported ${entries.length} pinned Tabler icons.`)
